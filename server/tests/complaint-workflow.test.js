import test from 'node:test';
import assert from 'node:assert/strict';
import express from 'express';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import router, { ticketScope } from '../routes/supportTickets.js';
import Ticket from '../models/SupportTicket.js';
import User from '../models/User.js';
import Job from '../models/NotificationJob.js';
import JSZip from 'jszip';
const root = fileURLToPath(new URL('../uploads/', import.meta.url));
const clientId = '507f1f77bcf86cd799439011', employeeId = '507f1f77bcf86cd799439022', id = '507f1f77bcf86cd799439033';
const body = { name: 'Complaint Person', cnic: '12345-1234567-1', category: 'Service Related Problem', serviceName: 'Trademark Registration', description: 'Please review this case', email: 'client@example.test', phone: '03001234567', clientId };
test('staff complaints support multiple protected uploads, client ownership, and admin deletion', async t => {
  let saved;
  const uploaded = [];
  t.after(async () => { await Promise.all(uploaded.map(name => fs.unlink(path.join(root, name)).catch(() => {}))); });
  t.mock.method(User, 'findOne', filter => ({ select: () => ({ lean: async () => filter._id === clientId ? { _id: clientId } : null }) }));
  t.mock.method(Ticket, 'create', async data => {
    saved = { ...data, _id: id, id, attachments: data.attachments.map((file, i) => ({ ...file, _id: `507f1f77bcf86cd7994390${i + 40}` })) };
    uploaded.push(...data.attachments.map(f => f.filename)); return saved;
  });
  t.mock.method(Job, 'findOneAndUpdate', async () => ({}));
  t.mock.method(Job, 'deleteMany', async filter => { assert.equal(filter.serviceId, id); assert.equal(filter.status, 'pending'); });
  t.mock.method(Ticket, 'findOne', filter => ({ lean: async () => {
    assert.equal(filter.deletedAt, null);
    return saved && !saved.deletedAt && (!filter.client || filter.client === saved.client) && (!filter.createdBy || filter.createdBy === saved.createdBy) ? saved : null;
  } }));
  t.mock.method(Ticket, 'findOneAndUpdate', async (filter, update) => { assert.equal(filter.deletedAt, null); saved = { ...saved, ...update.$set }; return saved; });
  const app = express(); app.use(express.json());
  app.use((req, res, next) => { const role = req.headers['x-test-role'] || 'user'; req.user = { role, id: role === 'employee' ? employeeId : role === 'admin' ? '507f1f77bcf86cd799439055' : req.headers['x-test-id'] || clientId, name: 'Test Staff' }; next(); });
  app.use(router);
  const server = app.listen(0, '127.0.0.1'); await new Promise(resolve => server.once('listening', resolve));
  t.after(() => new Promise(resolve => server.close(resolve)));
  const url = `http://127.0.0.1:${server.address().port}`;
  const form = new FormData(); Object.entries(body).forEach(([k, v]) => form.append(k, v));
  for (const name of ['first.pdf', 'first.pdf']) form.append('attachments', new Blob(['%PDF-1.4\nTest attachment'], { type: 'application/pdf' }), name);
  const created = await fetch(url, { method: 'POST', headers: { 'x-test-role': 'employee' }, body: form });
  assert.equal(created.status, 201, await created.text());
  assert.equal(saved.client, clientId); assert.equal(saved.createdBy, employeeId); assert.equal(saved.cnic, '1234512345671'); assert.equal(saved.attachments.length, 2);
  const attachmentUrl = `${url}/${id}/attachments/${saved.attachments[0]._id}`;
  const ownDownload = await fetch(attachmentUrl); assert.equal(ownDownload.status, 200); assert.match(ownDownload.headers.get('content-disposition'), /attachment/); assert.match(await ownDownload.text(), /%PDF/);
  const wrongClient = await fetch(attachmentUrl, { headers: { 'x-test-id': '507f1f77bcf86cd799439066' } }); assert.equal(wrongClient.status, 404);
  const staffDownload = await fetch(attachmentUrl, { headers: { 'x-test-role': 'employee' } }); assert.equal(staffDownload.status, 200); await staffDownload.arrayBuffer();
  const zipUrl = `${url}/${id}/attachments`;
  const zipResponse = await fetch(zipUrl); assert.equal(zipResponse.status, 200);
  assert.match(zipResponse.headers.get('content-disposition'), /attachments\.zip/);
  const zip = await JSZip.loadAsync(await zipResponse.arrayBuffer());
  assert.deepEqual(Object.keys(zip.files), ['01-first.pdf', '02-first.pdf']);
  assert.match(await zip.file('02-first.pdf').async('string'), /%PDF/);
  assert.equal((await fetch(zipUrl, { headers: { 'x-test-id': '507f1f77bcf86cd799439066' } })).status, 404);
  assert.equal((await fetch(`${url}/${id}`, { method: 'DELETE', headers: { 'x-test-role': 'employee' } })).status, 403);
  assert.equal((await fetch(`${url}/${id}`, { method: 'DELETE', headers: { 'x-test-role': 'admin' } })).status, 200);
  assert.equal((await fetch(attachmentUrl)).status, 404);
  assert.equal((await fetch(zipUrl)).status, 404);
  const adminCreated = await fetch(url, { method: 'POST', headers: { 'x-test-role': 'admin', 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
  assert.equal(adminCreated.status, 201); assert.equal(saved.createdByRole, 'admin'); assert.equal(saved.client, clientId);
  const missingService = await fetch(url, { method: 'POST', headers: { 'x-test-role': 'admin', 'Content-Type': 'application/json' }, body: JSON.stringify({ ...body, serviceName: '' }) });
  assert.equal(missingService.status, 400);
  const invalidFile = new FormData(); Object.entries(body).forEach(([k, v]) => invalidFile.append(k, v));
  invalidFile.append('attachments', new Blob(['<script>alert(1)</script>'], { type: 'application/pdf' }), 'fake.pdf');
  assert.equal((await fetch(url, { method: 'POST', body: invalidFile })).status, 400);
  const before = (await fs.readdir(root)).sort();
  const invalidForm = new FormData(); Object.entries({ ...body, cnic: 'bad' }).forEach(([k, v]) => invalidForm.append(k, v));
  invalidForm.append('attachments', new Blob(['%PDF-1.4\nValid bytes'], { type: 'application/pdf' }), 'cleanup.pdf');
  assert.equal((await fetch(url, { method: 'POST', body: invalidForm })).status, 400);
  assert.deepEqual((await fs.readdir(root)).sort(), before);
});
test('complaint scopes restrict employees to their submissions and clients to their own complaints', () => {
  assert.deepEqual(ticketScope({ role: 'employee', id: employeeId }), { deletedAt: null, createdBy: employeeId });
  assert.deepEqual(ticketScope({ role: 'user', id: clientId }), { deletedAt: null, client: clientId });
  assert.deepEqual(ticketScope({ role: 'admin' }), { deletedAt: null });
});
